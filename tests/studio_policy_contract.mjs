// Differential component contract: Python supplies same-state policy samples and controls
// from the real Reference; this process uses the actual TaskSim and MuJoCo WASM model.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import fs from "node:fs/promises";
import { TaskSim } from "../myoInteract/studio/static/sim.js";
import loadMujoco from "../myoInteract/studio/static/vendor/mujoco/mujoco.js";

assert.ok(process.argv[2], "provide the JSON artifact generated by test_studio_reference.py");
const artifact = JSON.parse(await fs.readFile(process.argv[2], "utf8"));
assert.match(artifact.native_mujoco_version, /^3\.\d+\.\d+$/);
const fixture = JSON.parse(await fs.readFile(process.argv[3] || new URL("./fixtures/studio/browser-3.15.0.json", import.meta.url), "utf8"));
assert.equal(fixture.format_version, 1);
assert.equal(fixture.native_mujoco_version, "3.15.0");
assert.equal(fixture.wasm_mujoco_version, "3.15.0");
assert.equal(fixture.examples.length, 5);
const browserExamples = new Map(fixture.examples.map((e) => [e.name, e]));
assert.equal(browserExamples.size, 5);
const examples = artifact.examples;
assert.equal(examples.length, 5, "the controller contract must cover every shipped simulation");
assert.equal(new Set(examples.map((e) => e.name)).size, 5);
const root = new URL("../myoInteract/studio/examples/", import.meta.url);
const mujoco = await loadMujoco();
assert.equal(mujoco.mj_versionString(), "3.15.0");
const physicsReports = [];

function difference(actual, expected, tolerance, label) {
  assert.equal(actual.length, expected.length, `${label}: shape`);
  let maximum = 0;
  for (let i = 0; i < actual.length; i++) {
    assert.ok(Number.isFinite(actual[i]) && Number.isFinite(expected[i]), `${label}[${i}]: finite values`);
    maximum = Math.max(maximum, Math.abs(actual[i] - expected[i]));
  }
  assert.ok(maximum <= tolerance, `${label}: maximum difference ${maximum} > ${tolerance}`);
  return maximum;
}

for (const example of examples) {
  assert.match(example.name, /^[a-z0-9-]+$/);
  assert.ok(example.cases.length >= 66, `${example.name}: include random samples, zero and initial observations`);
  const folder = new URL(`${example.name}/`, root);
  const info = JSON.parse(await fs.readFile(new URL("sim.json", folder), "utf8"));
  const bytes = await fs.readFile(new URL(info.policy, folder));
  const xml = await fs.readFile(new URL(info.model, folder), "utf8");
  const browser = browserExamples.get(example.name);
  assert.ok(browser, `${example.name}: browser engine profile`);
  assert.deepEqual(example.provenance, browser.provenance, `${example.name}: physics and actor asset provenance`);
  const sha256 = (value) => createHash("sha256").update(value).digest("hex");
  assert.equal(sha256(xml.replace(/\r\n/g, "\n")), browser.provenance.model_sha256, `${example.name}: model hash`);
  assert.equal(sha256(bytes), browser.provenance.policy_sha256, `${example.name}: policy hash`);
  const sim = new TaskSim(mujoco, info, xml,
    new Float32Array(bytes.buffer, bytes.byteOffset, bytes.byteLength / 4));
  try {
    const ref = browser.reference;
    assert.equal(ref.mujoco_version, fixture.native_mujoco_version);
    const fatigueState = ref.fatigue_state || [new Array(sim.model.nu).fill(0), new Array(sim.model.nu).fill(0), new Array(sim.model.nu).fill(1)];
    sim.reset({ start: ref.start, positions: ref.positions, sizes: ref.sizes, fatigueState });
    const initial = difference(sim.observe(), browser.initial_observation, 1e-6, `${example.name} browser engine initial observation`);
    assert.equal(browser.control_replay.length, ref.qpos.length, `${example.name}: replay every canonical control step`);
    const signature = browser.state_signature;
    assert.equal(signature, mujoco.mjtState.mjSTATE_INTEGRATION.value, `${example.name}: complete integration state`);
    const stateSize = mujoco.mj_stateSize(sim.model, signature);
    let maxLocalQpos = 0, maxLocalQvel = 0, worstLocalStep = -1;
    const localQposByStep = [];
    for (const [i, sample] of browser.control_replay.entries()) {
      assert.equal(sample.integration_before.length, stateSize, `${example.name} state step ${i}: shape`);
      assert.ok(sample.integration_before.every(Number.isFinite), `${example.name} state step ${i}: finite values`);
      // Include warmstart, time, activation and all other integration state. mj_step
      // recomputes derived quantities, so a separate mj_forward would add a solver pass.
      mujoco.mj_setState(sim.model, sim.data, new Float64Array(sample.integration_before), signature);
      sim.data.ctrl.set(sample.control);
      for (let k = 0; k < info.task.substeps; k++) mujoco.mj_step(sim.model, sim.data);
      const localQposError = difference(sim.data.qpos, sample.qpos, Infinity, `${example.name} same-state qpos step ${i}`);
      localQposByStep.push(localQposError);
      if (localQposError > maxLocalQpos) { maxLocalQpos = localQposError; worstLocalStep = i; }
      maxLocalQvel = Math.max(maxLocalQvel, difference(sim.data.qvel, sample.qvel, Infinity, `${example.name} same-state qvel step ${i}`));
      difference(sim.data.act, sample.act, 1e-6, `${example.name} same-state activation step ${i}`);
    }
    // The accumulated replay starts independently from reset: copying native states
    // above must not conceal a reset error or a divergence across repeated steps.
    sim.reset({ start: ref.start, positions: ref.positions, sizes: ref.sizes, fatigueState });
    let maxPhysicsQpos = 0, maxPhysicsQvel = 0, worstPhysicsStep = -1;
    const physicsQposByStep = [];
    for (const [i, sample] of browser.control_replay.entries()) {
      assert.equal(sample.control.length, sim.model.nu, `${example.name} control step ${i}: shape`);
      assert.ok(sample.control.every(Number.isFinite), `${example.name} control step ${i}: finite values`);
      // Replay exact fatigue-adjusted controls without state copies or policy feedback.
      // Build rounding can accumulate over 20 control frames; the original WASM rollout
      // budget is 5e-6, while the same-state integrator check retains the strict 1e-6 gate.
      sim.data.ctrl.set(sample.control);
      for (let k = 0; k < info.task.substeps; k++) mujoco.mj_step(sim.model, sim.data);
      // Collect the entire cross-platform error envelope before applying the separate
      // physics gates; a first failure must not hide later steps or other examples.
      const qposError = difference(sim.data.qpos, sample.qpos, Infinity, `${example.name} fixed-control qpos step ${i}`);
      physicsQposByStep.push(qposError);
      if (qposError > maxPhysicsQpos) { maxPhysicsQpos = qposError; worstPhysicsStep = i; }
      // Velocity has different units and is diagnostic; it does not share the position budget.
      maxPhysicsQvel = Math.max(maxPhysicsQvel, difference(sim.data.qvel, sample.qvel, Infinity, `${example.name} fixed-control qvel step ${i}`));
    }
    physicsReports.push({ name: example.name, maxQpos: maxPhysicsQpos, maxQvel: maxPhysicsQvel,
      worstStep: worstPhysicsStep, qposByStep: physicsQposByStep,
      maxLocalQpos, maxLocalQvel, worstLocalStep, localQposByStep });
    sim.reset({ start: ref.start, positions: ref.positions, sizes: ref.sizes, fatigueState });
    // The real step computes its excitation before physics. Keep the WASM state fixed here so
    // numerical controller differences cannot be hidden or amplified by a second simulation.
    sim.mj = { mj_step() {} };
    sim.noisy = false;
    let maxNormalized = 0, maxAction = 0, maxExcitation = 0;
    for (const [i, sample] of example.cases.entries()) {
      const observation = new Float32Array(sample.observation);
      const action = sim.act(observation);
      maxNormalized = Math.max(maxNormalized, difference(sim._normalized, sample.normalized, 1e-7, `${example.name} normalized sample ${i}`));
      maxAction = Math.max(maxAction, difference(action, sample.action, 1e-6, `${example.name} action sample ${i}`));
      sim.observe = () => observation;
      sim.step();
      maxExcitation = Math.max(maxExcitation, difference(sim._excitation, sample.excitation, 1e-7, `${example.name} excitation sample ${i}`));
    }
    console.log(`${example.name}: ${example.cases.length} native${artifact.native_mujoco_version} actor samples, browser${fixture.wasm_mujoco_version} initial=${initial}, normalized=${maxNormalized}, action=${maxAction}, excitation=${maxExcitation}, same-state qpos=${maxLocalQpos}, fixed-control qpos=${maxPhysicsQpos}, qvel=${maxPhysicsQvel}`);
  } finally { sim.dispose(); }
}
console.log(`Fixed-control physics diagnostics: ${JSON.stringify(physicsReports)}`);
for (const report of physicsReports) {
  assert.ok(report.maxLocalQpos <= 1e-6,
    `${report.name} same-state qpos step ${report.worstLocalStep}: maximum difference ${report.maxLocalQpos} > 0.000001`);
  assert.ok(report.maxQpos <= 5e-6,
    `${report.name} fixed-control qpos step ${report.worstStep}: maximum difference ${report.maxQpos} > 0.000005`);
}
